struct ppu {
    uint8_t PPUCTRL;    //$2000
    uint8_t PPUMASK;    //$2001
    uint8_t PPUSTATUS;  //$2002
    uint8_t OAMADDR;    //$2003 holds address in OAM to access on next write to $2004 
    uint8_t OAMDATA;    //$2004 write to OAM at address indicated by $2003
    uint8_t PPUSCROLL;  //$2005 VRAM address reg 1
    uint8_t PPUADDR;    //$2006 VRAM address reg 2
    uint8_t PPUDATA;    //$2007 reads or write byte from VRAM at curent address
    uint8_t OAMDMA;        //$4014
};


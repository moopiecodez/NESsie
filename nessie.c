void handle_events(bool *quit) {
    SDL_Event event;
    while (SDL_PollEvent(&event)) {
        switch (event.type) {
        case SDL_QUIT:
            *quit = true;
        }
    }
}

uint8_t read_mem(void *data, uint16_t address) {
    BYTE *memory = (BYTE *) data;
    uint8_t byte = memory[address];
    return byte;
}

void write_mem(void *data, uint16_t address, uint8_t byte) {
    BYTE *memory = (BYTE *) data;
    memory[address] = byte;
}


char *check_args(int argc, char *argv[]) {
    if (argc == 1) {
        printf("Error: no arguments provided\n");
        exit(1);
    } else if (argc > 2) {
        printf("Error: too many arguments, please specify just one file\n");
        exit(1);
    } else {
        return argv[1];
    }
}

int main(int argc, char *argv[]) {
    //set up components
    char *filename;
    Device cartridge;
    Device ram;
    //Device ppu; //placeholder
    //Device io;  //placeholder
    Bus bus;
    CPU *cpu;
    int ppuclock = 0;
    int masterclock = 0;
    int cpuclock = 0;

    //set up screen
    Uint32 init_flags = SDL_INIT_VIDEO;
    SDL_Init(init_flags);
    Screen screen = create_screen();

    //extract dummy graphics
    int i;
    int j;
    uint8_t plane1[8][8];
    uint8_t plane2[8][8];
    uint8_t result[8][8];
    for(i = 0; i < 8; i++) {
        for(j = 0; j < 8; j++) {
        plane1[i][j] = *(ptr + i) >> (7-j) & ~(~0<<1); //7-j is needed to get it in correct position in array which is reverse of bit position
        plane2[i][j] = *(ptr + i + 8) >> (7-j) & ~(~0<<1);
        result[i][j] = plane1[i][j] + plane2[i][j];
        printf("%d", result[i][j]);
        }    
    } 

    //load cartridge
    cpu = cpu_create();
    filename = check_args(argc, argv);
    cartridge = cartridge_load(filename);
    ram.data = memory;
    ram.read = &read_mem;
    ram.write = &write_mem;
    // io.data = io_mem;
    // io.read = &read_io;
    // io.write = &write_io;

    bus = bus_create(&cartridge, &ram);
    power_cpu(cpu);
        
    bool quit = false;

    while (!quit) {
        handle_events(&quit);
        //update game state
        if(masterclock % 4 == 0) {
            for(i = 0; i < 8; i++) {
                for(int j = 0; j < 8; j++) {
                    uint8_t pixel_on = result[i][j];
                    if(pixel_on != 0){
                        screen_pixel(screen, 0, 0, 255, j, i);
                    }
                }
            }
            screen_draw_frame(screen);
            ppuclock++;
        }
        if(masterclock % 12 == 0) {
            printf("Cycle: %03d| ", cpuclock);
            clocktick(cpu, bus);
            cpuclock++;
        }
    }
    SDL_Quit();
    return 0;
}

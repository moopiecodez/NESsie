char *check_args(int argc, char *argv[]) {
    if (argc == 1) {
        printf("Error: no arguments provided\n");
        exit(1);
    } else if (argc > 2) {
        printf("Error: too many arguments, please specify just one file\n");
        exit(1);
    } else {
        return argv[1];
    }
}

